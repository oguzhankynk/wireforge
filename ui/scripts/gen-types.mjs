// Generates the TypeScript types of the UI from the JSON Schema of project files and from the
// OpenAPI document of the server, so no model or API shape is written twice.
// Usage: node scripts/gen-types.mjs [--check]   (WIREFORGE_PYTHON selects the Python interpreter)
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const ui = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = dirname(ui);
const check = process.argv.includes("--check");
const header = "// Generated by ui/scripts/gen-types.mjs. Do not edit; run `npm run gen:types`.\n";

const schemaTypes = await compileFromFile(join(repo, "schema", "project.schema.json"), {
  bannerComment: "",
  cwd: join(repo, "schema"),
  additionalProperties: false,
  style: { printWidth: 100 },
});

// A type is a builtin name or a user identifier; both are strings, so the union collapses.
const schemaText = schemaTypes.replace(
  "export type TypeRef = BuiltinType | Identifier;",
  "export type TypeRef = Identifier; // a BuiltinType or the name of an enum or type",
);

const scratch = mkdtempSync(join(tmpdir(), "wireforge-openapi-"));
const openapiFile = join(scratch, "openapi.json");
const python = process.env.WIREFORGE_PYTHON ?? "python3";
execFileSync(
  python,
  ["-m", "wireforge.cli", "serve", "--workspace", scratch, "--openapi", openapiFile],
  { env: { ...process.env, PYTHONPATH: join(repo, "codegen") }, stdio: "ignore" },
);
const apiTypes = astToString(
  await openapiTS(JSON.parse(readFileSync(openapiFile, "utf8")), { defaultNonNullable: false }),
);
rmSync(scratch, { recursive: true, force: true });

const outputs = {
  [join(ui, "src", "generated", "schema.ts")]: header + schemaText,
  [join(ui, "src", "generated", "api.ts")]: header + apiTypes,
};
let stale = false;
for (const [path, text] of Object.entries(outputs)) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current === text) continue;
  if (check) {
    console.error(`${path} is outdated; run npm run gen:types`);
    stale = true;
  } else {
    writeFileSync(path, text);
  }
}
process.exit(stale ? 1 : 0);
