def _relative(target: Path, start: Path) -> str:
    """CMake path of `target`: relative to `start` when they share a directory, else absolute."""
    target, start = target.resolve(), start.resolve()
    try:
        common = Path(os.path.commonpath([target, start]))
    except ValueError:  # different drives on Windows
        return target.as_posix()
    if common == Path(common.anchor):
        return target.as_posix()
    return "${CMAKE_CURRENT_SOURCE_DIR}/" + Path(os.path.relpath(target, start)).as_posix()


def _profiles(project: Project) -> list[tuple[str, list[str]]]:
    """Per profile: target name suffix and compile definitions."""
    if not project.profiles:
        return [("", [])]
    result = []
    for profile in project.profiles.values():
        definitions = [f"{name}={value}" for name, value in profile.defines.items()]
        definitions.append(f"WIREFORGE_PROFILE_{profile.name}")
        result.append((f"_{profile.name}", definitions))
    return result


def executables(project: Project, kind: str) -> list[str]:
    """Names of the `tests`, `diff` or `fuzz` executables, one per profile."""
    return [f"{project.name}_{kind}{suffix}" for suffix, _ in _profiles(project)]


def _fill(template: str, values: dict[str, str]) -> str:
    for key, value in values.items():
        template = template.replace(f"@{key}@", value)
    return template


def sources(project: Project) -> tuple[str, ...]:
    """Return the test sources of the test executable (the vector test only with vectors)."""
    return (*SOURCES, VECTOR_SOURCE) if project.vectors else SOURCES


def _cmake(project: Project, directory: Path, location: Path, options: TestOptions) -> str:
    profiles = _profiles(project)
    values = {
        "TOOL": f"WireForge {versioning.TOOL_VERSION}",
        "NAME": project.name,
        "THRESHOLD": str(options.threshold),
        "RUNTIME": _relative(options.runtime, directory),
        "MODEL": _relative(location, directory),
        "SOURCES": " ".join(sources(project)),
        "INCLUDES": "".join(
            f" ${{WIREFORGE_MODEL_DIR}}/{path}" for path, _ in project.include_dirs
        ),
        "TARGETS": "".join(
            f'wireforge_add_profile("{suffix}"{"".join(" " + item for item in definitions)})\n'
            for suffix, definitions in profiles
        ),
        "TARGET_NAMES": " ".join(executables(project, "tests")),
    }
    model_dir = CMAKE_MODEL_DIR if project.include_dirs else ""
    return _fill(CMAKE_HEAD + model_dir + CMAKE_BODY, values)


def _presets(project: Project) -> str:
    variants = {
        "dev": {},
        "asan-ubsan": {"WIREFORGE_SANITIZE": "address,undefined"},
        "tsan": {"WIREFORGE_SANITIZE": "thread"},
        "coverage": {"WIREFORGE_COVERAGE": "ON"},
        "clang-tidy": {"WIREFORGE_CLANG_TIDY": "ON"},
    }
    configure = [
        {
            "name": name,
            "displayName": f"{project.name} tests ({name})",
            "binaryDir": f"${{sourceDir}}/build/{name}",
            "cacheVariables": {"CMAKE_BUILD_TYPE": "Debug", **cache},
        }
        for name, cache in variants.items()
    ]
    presets = {
        "version": 3,
        "cmakeMinimumRequired": {"major": 3, "minor": 21, "patch": 0},
        "configurePresets": configure,
        "buildPresets": [{"name": name, "configurePreset": name} for name in variants],
        "testPresets": [
            {"name": name, "configurePreset": name, "output": {"outputOnFailure": True}}
            for name in variants
        ],
    }
    return json.dumps(presets, indent=2) + "\n"


@dataclass(frozen=True)
class TestOptions:
    """Settings of the generated test project."""

    plugins: Path | None = None
    runtime: Path = RUNTIME_INCLUDE
    threshold: int = DEFAULT_COVERAGE


def render(
    project: Project, location: Path, directory: Path, options: TestOptions | None = None
) -> dict[str, str]:
    """Files of the test project (name -> content) for a project located at `location`.

    `directory` is where the files will be written; the CMake paths to the runtime headers and the
    project's include directories are relative to it. Raises CodecError when the reference codec
    cannot encode the samples (e.g. a custom checksum without plugin).
    """
    options = options or TestOptions()
    plugins = golden.load_plugins(options.plugins) if options.plugins else None
    golden_vectors = golden.vectors(project, plugins)
    profiles = test_cases.cases(project, plugins)
    report = layout.analyze(project)
    runs = vectors.run(project, plugins)
    names = ", ".join(f"`{name}`" for name in executables(project, "tests"))
    tool = f"WireForge {versioning.TOOL_VERSION}"
    threshold = options.threshold
    return {
        "CMakeLists.txt": _cmake(project, directory, location, options),
        "CMakePresets.json": _presets(project),
        ".clang-tidy": CLANG_TIDY.format(name=project.name),
        "README.md": README.format(
            name=project.name,
            tool=tool,
            executables=names,
            threshold=threshold,
            vector_note=VECTOR_NOTE if project.vectors else "",
        ),
        "test_support.hpp": cpp_tests.SUPPORT_HEADER,
        "wire_support.hpp": cpp_tests.WIRE_SUPPORT_HEADER,
        "diff_harness.cpp": cpp_tests.diff_harness_source(project),
        "fuzz_target.cpp": cpp_tests.fuzz_source(project),
        "selftest.cpp": cpp_tests.selftest_source(project, golden_vectors, profiles, runs),
        "handlers.hpp": cpp_tests.handlers_header(project),
        "golden_test.cpp": cpp_tests.golden_test_source(project, golden_vectors),
        "message_test.cpp": cpp_tests.message_test_source(project, profiles, report),
        "interface_test.cpp": cpp_tests.interface_test_source(project, profiles, report),
    } | (
        {VECTOR_SOURCE: cpp_tests.hlr_vector_test_source(project, runs)} if project.vectors else {}
    )


def write_test_project(
    project: Project, location: Path, output: Path, options: TestOptions | None = None
) -> list[Issue]:
    """Write `<output>/<project>/generated_tests/`; unchanged files are not rewritten."""
    directory = output / project.name / DIRECTORY
    try:
        files = render(project, location, directory, options)
    except CodecError as error:
        return [Issue(str(location), None, "", f"cannot compute the test expectations: {error}")]
    except CoveragePointError as error:
        return [Issue(str(location), None, "", str(error))]
    for name, text in files.items():
        target = directory / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
    return []
