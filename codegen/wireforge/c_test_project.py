"""Generated GoogleTest project for the C code of a project: `generated_tests/` for `--language c`.

The tests are C++ (GoogleTest) that call the generated C functions. The CMake project builds the
generated `model.c` as C99 with the warning set of C code as errors, one library and one test
executable per profile, and offers sanitizer presets and a `coverage` target that fails below 100
percent line, branch or function coverage of `model.c`.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

from wireforge import c_tests, golden, layout, test_cases, versioning
from wireforge.codec import CodecError
from wireforge.coverage_points import CoveragePointError
from wireforge.issues import Issue
from wireforge.test_project import (
    CMAKE_MODEL_DIR,
    DIRECTORY,
    TestOptions,
    fill_template,
    presets_text,
    profiles_of,
    relative_path,
)

if TYPE_CHECKING:
    from pathlib import Path

    from wireforge.model import Project

SOURCES = ("golden_test.cpp", "message_test.cpp")

CMAKE = """\
# Generated by @TOOL@ from project @NAME@. Do not edit; regenerate instead.
#
# Tests of the generated C code of @NAME@; see README.md.
cmake_minimum_required(VERSION 3.21)
project(@NAME@_generated_tests LANGUAGES C CXX)

set(CMAKE_C_STANDARD 99)
set(CMAKE_C_STANDARD_REQUIRED ON)
set(CMAKE_C_EXTENSIONS OFF)
set(CMAKE_CXX_STANDARD 17)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)
set(CMAKE_EXPORT_COMPILE_COMMANDS ON)

option(WIREFORGE_WERROR "Treat every warning as an error" ON)
option(WIREFORGE_COVERAGE "Instrument for coverage and add the coverage target" OFF)
set(WIREFORGE_SANITIZE "" CACHE STRING "Sanitizers: address,undefined or thread")
set(WIREFORGE_COVERAGE_MIN_LINE "@THRESHOLD@" CACHE STRING
    "Minimum line coverage of the generated code in percent")
set(WIREFORGE_COVERAGE_MIN_BRANCH "100" CACHE STRING
    "Minimum branch coverage of the generated code in percent")
set(WIREFORGE_COVERAGE_MIN_FUNCTION "100" CACHE STRING
    "Minimum function coverage of the generated code in percent")
set(WIREFORGE_RUNTIME_INCLUDE_DIR "@RUNTIME@" CACHE PATH
    "Directory holding the WireForge runtime headers (wireforge/c/*.h)")
get_filename_component(WIREFORGE_GENERATED_DIR "${CMAKE_CURRENT_SOURCE_DIR}/../.." ABSOLUTE)
if(NOT EXISTS "${WIREFORGE_RUNTIME_INCLUDE_DIR}/wireforge/c/status.h")
  message(FATAL_ERROR "Set WIREFORGE_RUNTIME_INCLUDE_DIR to the WireForge runtime/include dir")
endif()
"""

CMAKE_BODY = """\

# Compiler flags of the WireForge quality policy: C99 for the generated code, C++17 for the tests.
add_library(wireforge_c_flags INTERFACE)
add_library(wireforge_cxx_flags INTERFACE)
if(MSVC)
  target_compile_options(wireforge_c_flags INTERFACE /W4)
  target_compile_options(wireforge_cxx_flags INTERFACE /W4 /permissive- /Zc:__cplusplus)
  if(WIREFORGE_WERROR)
    target_compile_options(wireforge_c_flags INTERFACE /WX)
    target_compile_options(wireforge_cxx_flags INTERFACE /WX)
  endif()
else()
  target_compile_options(wireforge_c_flags INTERFACE
    -Wall -Wextra -Wpedantic -Wconversion -Wsign-conversion -Wshadow -Wcast-qual -Wcast-align
    -Wnull-dereference -Wdouble-promotion -Wformat=2 -Wundef -Wunused -Wswitch-enum
    -Wstrict-prototypes -Wold-style-definition -Wmissing-prototypes)
  target_compile_options(wireforge_cxx_flags INTERFACE
    -Wall -Wextra -Wpedantic -Wconversion -Wsign-conversion -Wshadow -Wold-style-cast
    -Wcast-align -Wcast-qual -Wnull-dereference -Wdouble-promotion -Wformat=2 -Wundef -Wunused
    -Wswitch-enum)
  if(WIREFORGE_WERROR)
    target_compile_options(wireforge_c_flags INTERFACE -Werror)
    target_compile_options(wireforge_cxx_flags INTERFACE -Werror)
  endif()
  foreach(flags wireforge_c_flags wireforge_cxx_flags)
    if(WIREFORGE_SANITIZE)
      target_compile_options(${flags} INTERFACE
        -fsanitize=${WIREFORGE_SANITIZE} -fno-omit-frame-pointer -fno-sanitize-recover=all)
      target_link_options(${flags} INTERFACE -fsanitize=${WIREFORGE_SANITIZE})
    endif()
    if(WIREFORGE_COVERAGE)
      target_compile_options(${flags} INTERFACE --coverage -O0 -g)
      target_link_options(${flags} INTERFACE --coverage)
    endif()
  endforeach()
endif()

find_package(GTest 1.14 QUIET)
if(NOT GTest_FOUND)
  include(FetchContent)
  set(INSTALL_GTEST OFF CACHE BOOL "" FORCE)
  set(gtest_force_shared_crt ON CACHE BOOL "" FORCE)
  FetchContent_Declare(googletest
    GIT_REPOSITORY https://github.com/google/googletest.git
    GIT_TAG v1.14.0
    GIT_SHALLOW TRUE
    SYSTEM)
  FetchContent_MakeAvailable(googletest)
endif()
find_package(Threads REQUIRED)
include(GoogleTest)
enable_testing()

# wireforge_add_profile(<suffix> <definitions...>): the C library and the tests of one profile
# (@NAME@_model<suffix>, @NAME@_tests<suffix>).
function(wireforge_add_profile suffix)
  set(includes ${WIREFORGE_GENERATED_DIR} ${WIREFORGE_RUNTIME_INCLUDE_DIR}@INCLUDES@)
  set(model @NAME@_model${suffix})
  add_library(${model} STATIC ${WIREFORGE_GENERATED_DIR}/@NAME@/model.c)
  target_include_directories(${model} PRIVATE ${includes})
  target_compile_definitions(${model} PRIVATE ${ARGN})
  target_link_libraries(${model} PRIVATE wireforge_c_flags)
  set(tests @NAME@_tests${suffix})
  add_executable(${tests} @SOURCES@)
  # The generated header and the runtime are C code: their headers are system headers here, so
  # that the warnings of the C++ test code are not raised for them.
  target_include_directories(${tests} PRIVATE ${CMAKE_CURRENT_SOURCE_DIR})
  target_include_directories(${tests} SYSTEM PRIVATE ${includes})
  target_compile_definitions(${tests} PRIVATE ${ARGN})
  target_link_libraries(${tests} PRIVATE ${model} GTest::gtest_main Threads::Threads
                        wireforge_cxx_flags)
  gtest_discover_tests(${tests} DISCOVERY_MODE PRE_TEST
                       XML_OUTPUT_DIR ${CMAKE_BINARY_DIR}/results/junit/${tests})
endfunction()

@TARGETS@
if(WIREFORGE_COVERAGE)
  find_program(WIREFORGE_GCOVR gcovr REQUIRED)
  if(CMAKE_C_COMPILER_ID MATCHES "Clang")
    set(WIREFORGE_GCOV "llvm-cov gcov" CACHE STRING "gcov command used by gcovr")
  else()
    set(WIREFORGE_GCOV "gcov" CACHE STRING "gcov command used by gcovr")
  endif()
  # Runs the tests, then reports the line, branch and function coverage of model.c. The
  # machine-readable results are written to <build>/results.
  set(WIREFORGE_RESULTS_DIR ${CMAKE_BINARY_DIR}/results)
  add_custom_target(coverage
    COMMAND ${CMAKE_COMMAND} -E make_directory ${WIREFORGE_RESULTS_DIR}
    COMMAND ${CMAKE_CTEST_COMMAND} --test-dir ${CMAKE_BINARY_DIR} --output-on-failure
            --output-junit ${WIREFORGE_RESULTS_DIR}/ctest.xml
    COMMAND ${CMAKE_COMMAND} -E make_directory ${CMAKE_BINARY_DIR}/coverage
    COMMAND ${WIREFORGE_GCOVR} --root ${WIREFORGE_GENERATED_DIR}
            --object-directory ${CMAKE_BINARY_DIR} --gcov-executable ${WIREFORGE_GCOV}
            --gcov-ignore-errors=source_not_found
            --filter "@NAME@/model[.]c"
            --txt --html-details ${CMAKE_BINARY_DIR}/coverage/index.html
            --json ${WIREFORGE_RESULTS_DIR}/coverage.json
            --json-summary ${WIREFORGE_RESULTS_DIR}/coverage_summary.json
            --cobertura ${WIREFORGE_RESULTS_DIR}/coverage.cobertura.xml
            --fail-under-line ${WIREFORGE_COVERAGE_MIN_LINE}
            --fail-under-branch ${WIREFORGE_COVERAGE_MIN_BRANCH}
            --fail-under-function ${WIREFORGE_COVERAGE_MIN_FUNCTION}
    WORKING_DIRECTORY ${WIREFORGE_GENERATED_DIR}
    DEPENDS @TARGET_NAMES@
    VERBATIM)
endif()
"""

README = """\
# Generated tests of the C code of {name}

Generated by {tool}. Do not edit; regenerate instead.

GoogleTest suites for the generated C99 code of `{name}` (`{name}/model.h`, `{name}/model.c`). The
tests are C++ and call the C functions. Every expectation comes from the WireForge reference codec:

- `golden_test.cpp`: golden vectors round-trip through `serialize` and `deserialize`;
- `message_test.cpp`: defaults, minimum/maximum and out-of-range values, empty arrays, invalid enum
  values, decode errors (wrong checksum, count above the maximum, constants, truncation) and the
  physical values of fields with a scale.

Profiles are separate executables: {executables}.

```sh
cmake --preset dev && cmake --build --preset dev && ctest --preset dev
cmake --preset coverage && cmake --build --preset coverage --target coverage
cmake --preset asan-ubsan && cmake --build --preset asan-ubsan && ctest --preset asan-ubsan
```

`WIREFORGE_RUNTIME_INCLUDE_DIR` points to the WireForge runtime headers. The `coverage` target
needs gcovr and fails below `WIREFORGE_COVERAGE_MIN_LINE` percent line coverage (default
{threshold}) or below 100 percent branch and function coverage of `model.c`. GoogleTest 1.14 is
taken from the system or downloaded.
"""


def executables(project: Project) -> list[str]:
    """Return the names of the test executables, one per profile."""
    return [f"{project.name}_tests{suffix}" for suffix, _ in profiles_of(project)]


def _cmake(project: Project, directory: Path, location: Path, options: TestOptions) -> str:
    values = {
        "TOOL": f"WireForge {versioning.TOOL_VERSION}",
        "NAME": project.name,
        "THRESHOLD": str(options.threshold),
        "RUNTIME": relative_path(options.runtime, directory),
        "MODEL": relative_path(location, directory),
        "SOURCES": " ".join(SOURCES),
        "INCLUDES": "".join(
            f" ${{WIREFORGE_MODEL_DIR}}/{path}" for path, _ in project.include_dirs
        ),
        "TARGETS": "".join(
            f'wireforge_add_profile("{suffix}"{"".join(" " + item for item in definitions)})\n'
            for suffix, definitions in profiles_of(project)
        ),
        "TARGET_NAMES": " ".join(executables(project)),
    }
    model_dir = CMAKE_MODEL_DIR if project.include_dirs else ""
    return fill_template(CMAKE + model_dir + CMAKE_BODY, values)


def render(
    project: Project, location: Path, directory: Path, options: TestOptions | None = None
) -> dict[str, str]:
    """Return the files of the C test project (name -> content).

    Raises CodecError when the reference codec cannot encode the samples (for example a custom
    checksum without a plugin) and CoveragePointError when a required test is missing.
    """
    options = options or TestOptions()
    plugins = golden.load_plugins(options.plugins) if options.plugins else None
    golden_vectors = golden.vectors(project, plugins)
    profiles = test_cases.cases(project, plugins)
    report = layout.analyze(project)
    presets = json.loads(presets_text(project))
    for preset in presets["configurePresets"]:
        preset["cacheVariables"].pop("WIREFORGE_CLANG_TIDY", None)
    keep = {"dev", "asan-ubsan", "tsan", "coverage"}
    presets["configurePresets"] = [p for p in presets["configurePresets"] if p["name"] in keep]
    presets["buildPresets"] = [p for p in presets["buildPresets"] if p["name"] in keep]
    presets["testPresets"] = [p for p in presets["testPresets"] if p["name"] in keep]
    tool = f"WireForge {versioning.TOOL_VERSION}"
    names = ", ".join(f"`{name}`" for name in executables(project))
    return {
        "CMakeLists.txt": _cmake(project, directory, location, options),
        "CMakePresets.json": json.dumps(presets, indent=2) + "\n",
        "README.md": README.format(
            name=project.name, tool=tool, executables=names, threshold=options.threshold
        ),
        "api.hpp": c_tests.api_header(project),
        "test_support.hpp": c_tests.SUPPORT_HEADER,
        "golden_test.cpp": c_tests.golden_test_source(project, golden_vectors),
        "message_test.cpp": c_tests.message_test_source(project, profiles, report, plugins),
    }


def write_test_project(
    project: Project, location: Path, output: Path, options: TestOptions | None = None
) -> list[Issue]:
    """Write `<output>/<project>/generated_tests/`; unchanged files are not rewritten."""
    directory = output / project.name / DIRECTORY
    try:
        files = render(project, location, directory, options)
    except CodecError as error:
        return [Issue(str(location), None, "", f"cannot compute the test expectations: {error}")]
    except CoveragePointError as error:
        return [Issue(str(location), None, "", str(error))]
    for name, text in files.items():
        target = directory / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
    return []
