"""The system test project: every sender's encoder against every receiver's decoder.

For each interface of a project with `nodes`, each message, each sender of it and each other
participant of the interface, the generated test encodes the golden value with the sender's
generated code, hands the frame to the receiver's generated link and decoder, and compares what the
receiver decoded with the golden payload. The C++ code of all units is built into one GoogleTest
executable (the namespaces keep the units apart); a unit whose language is C is linked as a static
library (its prefix keeps the names apart). The project is written to `<output>/system/`, next to
the unit directories it uses.
"""

